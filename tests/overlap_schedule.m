function overlap_schedule(varargin)
% OVERLAP_SCHEDULE  겹침 기반 천이 설계 : 방법론 전체를 한 파일에 담은 것
%
% ========================================================================
%  무엇을 하는 코드인가
% ========================================================================
%   제자리 비행에서 순항 비행으로 넘어가는 천이 스케줄을 구한다.  구체적으로는
%   구간마다 쓸 전진 가속도 a_k 를 정한다.
%
%   관행적인 방법은 트림점마다 기체가 완전히 안정될 때까지 기다린 뒤 다음
%   트림점으로 넘어간다.  안전하지만 이 기체에서는 약 9분이 걸리고, 그중
%   8분이 기다리는 시간이다.
%
%   이 코드는 기다리지 않는다.  대신 이웃한 두 트림점의 BRT(안전영역)가 서로
%   겹치는지를 따진다.  겹치면 기체는 앞 트림점의 보증을 잃기 전에 뒤 트림점의
%   보증을 얻으므로, 되돌아갈 곳이 없는 순간이 생기지 않는다.
%
%   온라인 최적화도 예측 시뮬레이션도 쓰지 않는다.  미리 구해 둔 BRT 값함수를
%   조회하고 대수식을 계산하는 것으로 끝난다.
%
% ========================================================================
%  실행 방법
% ========================================================================
%       matlab -batch "addpath(genpath('.')); overlap_schedule"
%
%   선택 인자 (이름-값 쌍)
%       'tau_mode'    'anchor'(기본) | 'uniform'
%                     시정수를 트림점마다 다르게 쓸지, 하나로 통일할지.
%                     uniform 으로 하면 24.67초가 나오지만 순항 진입에서
%                     30초 중 19.7% 가 BRT 를 벗어난다.
%       'tau_uniform' 1.29 [초]  uniform 일 때 쓰는 값.  anchor 모드에서는
%                     선형모델에서 뽑은 tau 를 이 값에 맞춰 눈금 조정한다.
%       'verify'      true       비선형 시뮬레이터 검증 실행 여부
%       'recompute_c' false      계수 c 를 다시 측정할지 (약 3분 걸림)
%       'cruise_hold' 30 [초]    순항 유지 검사 길이
%       'save'        true       logger/overlap_schedule.mat 에 저장
%
% ========================================================================
%  변수 사전
% ========================================================================
%
%  --- D : 준비물 묶음 (load_inputs 가 만든다) -----------------------------
%   D.UH      1x20   앵커(트림점) 20개의 전진속도            [ft/s]
%                    0, 8.44, 16.88, ... , 160.0
%   D.TL      4x20   각 앵커의 트림 상태, 지평선 기준
%                    행 1 = u  전진속도                      [ft/s]
%                    행 2 = w  수직속도 (전부 11.667, 강하)  [ft/s]
%                    행 3 = q  피치각속도 (전부 0)           [rad/s]
%                    행 4 = th 피치각 (0.011 ~ 0.099)        [rad]
%   D.du      1x19   이웃 앵커 사이의 속도 간격              [ft/s]
%                    앞 18개는 8.439, 마지막만 8.101
%   D.dthdu   1x20   트림 피치각이 속도에 따라 기우는 기울기 [rad/(ft/s)]
%                    피치각속도 편차를 구할 때 빼 주는 몫
%   D.SH      3x19   이웃 앵커 사이의 가로성분 차이
%                    행 1 = w 차이 (전부 0),  행 2 = q 차이 (전부 0)
%                    행 3 = th 차이 (0.003 ~ 0.007 rad)
%                    e 를 앵커 k+1 기준으로 옮길 때 더한다
%   D.GMIN    4x1    BRT 격자의 아래 모서리  [-16; -33; -1.5; -0.75]
%   D.GMAX    4x1    BRT 격자의 위 모서리    [+16; +33; +1.5; +0.75]
%                    순서는 [du; dw; dq; dth],  단위 [ft/s; ft/s; rad/s; rad]
%   D.V       1x20   BRT 값함수 20개.  각각 griddedInterpolant 객체이고
%                    V{k}(du, dw, dq, dth) <= 0 이면 앵커 k 의 안전영역 안.
%                    격자 크기는 21 x 41 x 61 x 31
%   D.a_hi    1x19   공력 모델이 유효한 범위에서 나온 가속도 상한 [ft/s^2]
%                    (logger/accel_limits.mat 에서 읽는다)
%
%  --- 추종오차를 기술하는 두 계수 -----------------------------------------
%   C         4x20   가속도 1 ft/s^2 당 각 앵커에서 벌어지는 정상 편차
%                    행 1 = c_u   전진속도 편차             [s]
%                    행 2 = c_w   수직속도 편차             [s]
%                    행 3 = c_q   피치각속도 편차 (안 씀)
%                    행 4 = c_th  피치각 편차               [rad/(ft/s^2)]
%                                 앵커 1 에서 -0.0333 (-1.91 도)
%                                 앵커 19 에서 -0.0531 (-3.04 도)
%                    d = a * c 가 그 가속도에서 향해 가는 점근값이 된다.
%                    도달하는 값이 아니라 과도응답의 크기 인자로만 쓴다.
%   GT        1x15   g(t) 표의 시각 눈금                    [초]
%   GV        1x15   g(t) 표의 값 (정규화된 계단응답, 무차원)
%                    0.75초 0.18,  1.29초 0.63,  3.0초 1.23(첨두),  8초 1.02
%                    닫힌 형태로는 zeta=0.42, wn=1.16 rad/s 인 2차계 응답
%   GD        1x15   g'(t).  피치각속도 편차를 구할 때 쓴다
%   TAU       1x19   앵커별 시정수, 편차가 d 의 63% 에 닿는 시각  [초]
%                    1.29 (호버) ~ 1.93 (순항).  1.5배 차이가 난다
%
%  --- P : 계산에 쓰는 것들을 묶은 것 (함수에 넘기려고) --------------------
%   P.C, P.GT, P.GV, P.GD, P.du, P.dthdu, P.SH, P.V, P.GMIN, P.GMAX
%                    위와 같다.  이름만 옮겨 담았다
%
%  --- 풀이 과정에서 쓰는 것 ----------------------------------------------
%   a         1x19   구하려는 답.  구간별 전진 가속도         [ft/s^2]
%   tj        1x20   각 구간이 시작하는 시각                  [초]
%                    tj(1) = 0,  tj(k+1) = tj(k) + du(k)/a(k)
%   dD        2x19   각 구간이 새로 얹는 "계단"의 크기
%                    행 1 = dw 성분 [ft/s],  행 2 = dth 성분 [rad]
%                    Dd_k = a_k*c_k - a_{k-1}*c_{k-1}
%                    편차를 새로 만드는 것은 가속도가 아니라 그 변화량이다.
%                    앞 구간과 같은 가속도면 새 계단이 얹히지 않는다
%   e         3x1    가로 편차.  BRT 를 자르는 위치
%                    e(1) = dw   수직속도 편차                [ft/s]
%                    e(2) = dq   피치각속도 편차              [rad/s]
%                    e(3) = dth  피치각 편차                  [rad]
%                    du 는 e 에 들어가지 않는다.  겹침을 재는 축이기 때문
%   L, H      스칼라 e 에서 자른 단면에서 BRT 가 차지하는 du 구간의 양 끝
%                    각자의 트림점을 0 으로 삼아 잰다           [ft/s]
%                    L 은 대개 음수여서 H-L 이 실제로는 더하기로 작동한다
%
%  --- info : 풀이 결과의 내역 ---------------------------------------------
%   info.cap_tau  1x19  성립조건 상한  du(k)/tau(k)           [ft/s^2]
%   info.cap_aero 1x19  공력 유효범위 상한 (= D.a_hi)         [ft/s^2]
%   info.a_safe   1x19  안전조건만 걸었을 때 갈 수 있는 최대  [ft/s^2]
%   info.slack    1x19  고른 a 에서의 가장 얇은 겹침 여유      [ft/s]
%   info.bind     1x19  무엇이 묶었는지 ('안전조건'/'성립조건'/'공력범위')
%   info.tj, info.dD    위의 tj, dD
%
%  --- R : 시뮬레이터 검증 결과 --------------------------------------------
%   R.cov         1x19 논리  구간마다 인계가 실제로 일어났는가
%   R.worst       1x19  구간마다 min(V_k, V_k+1) 의 최댓값
%                       음수면 항상 둘 중 하나 안에 있었다는 뜻
%   R.out_pct     1x19  구간마다 두 영역 모두 밖이었던 스텝의 비율 [%]
%   R.n_out, R.n_tot    천이 전체에서 밖이었던 스텝 수 / 전체 스텝 수
%   R.cruise_worst      순항 유지 중 앵커 20 값함수의 최댓값
%   R.cruise_out, R.cruise_n   순항에서 밖이었던 스텝 수 / 전체
%
% ========================================================================
%  차례 (문서의 절 번호와 대응한다)
% ========================================================================
%   0절  준비물을 읽어들인다
%   1절  계수 c 와 g, 시정수 tau                      [문서 1.6, 1.7, 부록]
%   2절  판정식 : 단면의 u 구간과 겹침                [문서 1.5]
%   3절  예측식 : 계단 중첩으로 e 를 만든다           [문서 1.6]
%   4절  풀이 : 앞에서부터 가장 큰 a 를 고른다        [문서 1.8]
%   5절  검증 : 비선형 시뮬레이터로 날린다            [문서 2.7]
%
%  기본 설정 결과 : 천이시간 28.93초, 천이 중 BRT 위배 0, 순항 30초 위배 0.
%  시뮬레이터를 전수 탐색해 얻은 28.54초와 1.4% 차이.

% ------------------------------------------------------------------------
%% 0절  설정과 준비물
% ------------------------------------------------------------------------
OPT  = parse_opts(varargin{:});
root = fileparts(fileparts(mfilename('fullpath')));   % 저장소 최상단

D = load_inputs(root);          % 트림점, BRT, 공력 유효범위

% ------------------------------------------------------------------------
%% 1절  계수 c 와 g, 시정수 tau
% ------------------------------------------------------------------------
%  기체가 가속하면 트림점에서 밀려난다.  그 밀려남을 두 가지가 결정한다.
%
%    얼마나 멀리 가는가  ->  d = a * c        (c 는 폐루프의 성질, 고르는 값 아님)
%    얼마나 빨리 가는가  ->  e(t) = d * g(t)  (g 는 정규화된 계단응답)
%
%  중요 : 편차는 0 으로 수렴하지 않는다.  가속하려면 기수를 숙여야 하고 트림
%  자세는 정의상 가속도가 0 인 자세이므로, 가속하는 동안에는 트림 자세에 있을
%  수가 없다.  편차는 d 라는 0 이 아닌 값으로 수렴한다.  그래서 이 방법론이
%  트림점을 지나가지 않으면서도 성립한다.
C        = get_gain(root, D, OPT);   % 4 x 20
[GT, GV] = get_shape(root);          % g(t) 표
GD       = gradient(GV, GT);         % g'(t)
TAU      = get_tau(root, OPT);       % 1 x 19

% ------------------------------------------------------------------------
%% 4절  풀이
% ------------------------------------------------------------------------
P = struct('C',C, 'GT',GT, 'GV',GV, 'GD',GD, 'du',D.du, ...
           'dthdu',D.dthdu, 'SH',D.SH, 'V',{D.V}, ...
           'GMIN',D.GMIN, 'GMAX',D.GMAX);

[a, info] = solve_schedule(P, D.a_hi, TAU);
report_schedule(D, a, info, TAU);

% ------------------------------------------------------------------------
%% 5절  검증
% ------------------------------------------------------------------------
%  여기서 시뮬레이터를 쓰는 것은 a 를 찾기 위해서가 아니라 이미 나온 답을
%  검사하기 위해서다.  방법론 자체에는 시뮬레이션이 들어가지 않는다.
vres = [];
if OPT.verify
    vres = verify_schedule(D, a, OPT.cruise_hold);
    report_verify(vres, sum(D.du./a));
end

if OPT.save
    out = fullfile(root,'logger','overlap_schedule.mat');
    save(out, 'a', 'info', 'TAU', 'C', 'GT', 'GV', 'vres', 'OPT');
    fprintf('\n  저장 : %s\n', out);
end
end


%% ========================================================================
%  0절  준비물을 읽어들인다
%  ========================================================================
function D = load_inputs(root)
% 트림점 20개, BRT 20개, 공력 모델 유효범위를 읽는다.

T = load('trim_table_Poly_ConcatVer4p0.mat');

% 앵커 속도.  0 에서 160 ft/s 까지 20개, 간격은 8.44 로 균일하다.
D.UH = T.UH(1:20).';

% 트림 상태를 [u; w; q; th] 로 뽑는다.
%   XU0_interp 의 행 순서가 [1 3 5 11] 인 것은 트림표의 저장 순서 때문이다.
%   세 번째 첨자 3 은 WH(3) = 11.667 ft/s 강하 조건을 뜻한다.
%   이 기체의 트림점은 전부 분당 700피트 강하 조건에서 구해졌으므로,
%   임무도 같은 조건이어야 한다.  수평으로 날면 상시로 11.7 의 수직속도
%   편차를 안고 날게 되어 BRT 여유를 세 배 가까이 손해 본다.
D.TL = T.XU0_interp([1 3 5 11], 1:20, 3);

D.du    = diff(D.UH);                         % 트림 간격 [ft/s]
D.dthdu = gradient(D.TL(4,:), D.UH);          % 트림 피치각의 속도 기울기

% 이웃 트림점 사이의 가로성분 차이.  판정식에서 e 를 앵커 k+1 기준으로
% 옮길 때 더한다.  두 BRT 의 중심 높이가 다르기 때문이다.
% 이 기체에서 실제로 다른 것은 자세뿐이다 (w_trim 은 전부 11.667, q_trim 은 0).
% 차이는 0.19 ~ 0.39 도로 작고, 반영해도 천이시간은 바뀌지 않는다.
D.SH = D.TL(2:4, 1:19) - D.TL(2:4, 2:20);

% BRT 격자 규격.  네 축은 [du, dw, dq, dth] 이고 격자점 수는 21/41/61/31.
spec   = FilterConfig.channelSpec('lon');
D.GMIN = spec.grid_min;    % [-16; -33; -1.5; -0.75]
D.GMAX = spec.grid_max;    % [+16; +33; +1.5; +0.75]
gv = cell(1,4);
for i = 1:4
    gv{i} = linspace(spec.grid_min(i), spec.grid_max(i), spec.grid_num(i));
end

% BRT 값함수 20개를 보간기로 만들어 둔다.  V{k}(du,dw,dq,dth) <= 0 이면
% 앵커 k 의 안전영역 안, 즉 적절히 조종해서 그 트림점으로 되돌아올 수 있다.
D.V = cell(1,20);
for k = 1:20
    S = load(fullfile(root,'data', ...
        sprintf('GUAM_LON_BRT_HJIR_UH%d_WH%d.mat', k, 3)), 'data');
    D.V{k} = griddedInterpolant(gv, S.data, 'linear', 'nearest');
end

% 공력 모델이 유효한 범위에서 나온 가속도 상한.  BRT 조건과는 별개인
% 기체 쪽 제약이다.  앵커 1 은 Inf, 고속에서 8.8 까지 내려온다.
AL = load(fullfile(root,'logger','accel_limits.mat'));
D.a_hi = AL.a_hi;
end


%% ========================================================================
%  1절  계수와 시정수
%  ========================================================================
function C = get_gain(root, D, OPT)
% c_k : 가속도 1 ft/s^2 당 앵커 k 에서 벌어지는 정상 편차.
%
%   이것은 튜닝하는 값이 아니라 폐루프에서 측정되는 성질이다.  기본은 저장된
%   값을 읽고, 다시 재려면 recompute_c 를 켠다.  재는 방법은 파일 끝의
%   measure_gain 에 적혀 있다.
%
%   검증 결과 (일정 가속도로 길게 날려서 확인)
%     - a 에 대한 비례성이 성립한다.  가속도를 다섯 배로 키워도 같은 속도에서
%       dth/a 가 유지된다.  우리가 쓰는 범위(a = 4~7)에서 예측 대비 오차 1.5~5%
%     - a = 1 에서만 어긋나는데 편차 자체가 1.5도 정도로 작아 잡음에 묻힌다
f = fullfile(root,'logger','dev_gain.mat');
if OPT.recompute_c || ~isfile(f)
    C = measure_gain(root, D);
    save(f, 'C', '-append');
    fprintf('  계수 c 를 다시 쟀습니다.\n');
else
    S = load(f, 'C');  C = S.C;
end
end


function [GT, GV] = get_shape(root)
% g(t) : 정규화된 계단응답.  편차가 정상값 d 를 향해 자라나는 모양이다.
%
%   실측한 표를 그대로 쓴다.  닫힌 형태로 쓰면 표준 2차계 계단응답이다.
%
%       g(t) = 1 - exp(-z*wn*t) * ( cos(wd*t) + (z*wn/wd)*sin(wd*t) )
%
%   z (감쇠비) = 0.42,  wn (고유진동수) = 1.16 rad/s,  wd = 1.05 rad/s
%   실측한 첨두 초과 23% 와 첨두 시각 3.0초에서 역산한 값이다.
%
%   왜 1차계가 아니라 2차계인가 : 1차계 응답은 최종값을 결코 넘지 못하는데
%   실측은 1.35배까지 올라갔다 되돌아온다.  물리적으로도 자세는 관성을 가진
%   회전 운동이고 제어기가 자세와 자세율을 함께 되먹이므로 복소 극 한 쌍이
%   생긴다.  z 와 wn 은 그 극 한 쌍을 두 실수로 바꿔 적은 것이다.
%
%   검증 결과 : 진폭을 바꿔도 형태가 같다.  t = 1.29초의 정규화값이
%   a = 1, 2, 3, 5 에서 0.65, 0.68, 0.66, 0.67 로 5% 이내로 일치한다.
%   이것이 계단들을 그냥 더할 수 있는 근거(선형성)를 직접 확인한 결과다.
%
%   주의 : 이 표는 첨두를 실측 1.35 대신 1.23 으로 낮게 본다.  약 10% 를
%   과소평가하며 이것은 안전하지 않은 방향이다.  여유가 얇은 구간에서는
%   이 몫을 감안해야 한다.
S  = load(fullfile(root,'logger','dev_gain.mat'), 'GT', 'GV');
GT = S.GT;  GV = S.GV;
end


function TAU = get_tau(root, OPT)
% tau_k : 편차가 정상값 d 의 63% 에 닿는 시각.  트림점마다 다르다.
%
%   tau 는 편차가 0 으로 가는 시간이 아니다.  d 자체가 0 이 아니므로,
%   "그 계가 가려는 값" 의 63% 에 닿는 시간이라는 뜻이다.
%
%   [뽑는 방법이 중요하다]
%   고윳값에서 뽑으면 안 된다.  이 폐루프는 상태가 34개이고 위치오차와
%   적분기가 섞여 있는데, 가장 느린 극이 |z| = 0.999 (시정수 약 10초) 이다.
%   그 모드는 위치오차와 적분기에 76~98% 살고 있어 자세 응답에는 거의
%   기여하지 않는데도, 기여도로 가중평균하면 새어 들어와 2.88초라는 오염된
%   값이 나온다 (비선형 실측은 1.29초).
%
%   그래서 정의로 돌아간다.  폐루프를 가속도 계단으로 굴려 63% 도달 시각을
%   직접 읽는다.  움직이는 평형점 기준 편차의 점화식은 다음과 같다.
%
%       delta(n+1) = Phi_k * delta(n) - (dxi_e/dv)_k * a * dt
%
%   Phi 는 폐루프의 한 걸음 전이행렬, xi_e(v) 는 속도 v 에서의 평형점이다.
%   가속하면 평형점이 매 걸음 움직이므로 뒷항이 붙는다.  이 식을 굴리면
%   계단응답이 그대로 그려진다.
%
%   [왜 앵커마다 달라야 하는가]
%   tau 를 가장 빠른 값 하나로 통일하면 고속 구간이 너무 짧아진다.  실제로
%   19개 중 15개 구간이 자기 성립조건을 위반하게 되고, 그 대가가 천이 자체가
%   아니라 순항 진입에서 나타난다.  미처 가라앉지 못한 편차를 안고 순항에
%   들어가므로 순항 30초 중 19.7% 에서 BRT 를 벗어난다.
if strcmpi(OPT.tau_mode, 'uniform')
    TAU = repmat(OPT.tau_uniform, 1, 19);
    return
end

S  = load(fullfile(root,'logger','closed_loop_model_descending.mat'));
M  = S.M;                      % ClosedLoopModel 객체
dt = M.dt;                     % 0.01 초
UA = M.u_anchor;               % 앵커 속도
XE = M.xi_e;                   % 34 x 20, 앵커마다의 평형점

% 평형점이 속도에 따라 움직이는 기울기 dxi_e/dv
dXE = zeros(size(XE));
for j = 1:size(XE,1)
    dXE(j,:) = gradient(XE(j,:), UA);
end

n = numel(UA);  T63 = zeros(1,n);
for k = 1:n
    d   = zeros(M.N_XI, 1);          % 편차, 0 에서 출발
    drv = dXE(:,k) * 5.0 * dt;       % 가속도 5 에 해당하는 구동항
    H   = zeros(1, round(15/dt));    % 15초간 굴린다
    for i = 1:numel(H)
        d    = M.Phi{k}*d - drv;
        H(i) = d(8);                 % 34개 상태 중 8번째가 피치각
    end
    H  = H / H(end);                 % 최종값으로 정규화
    tl = (1:numel(H)) * dt;
    T63(k) = tl(find(H >= 0.632, 1, 'first'));
end

% 선형모델은 호버에서 1.38초를 주는데 비선형 실측은 1.29초다.
% 같은 비율로 전체 눈금을 맞춘다.
TAU = T63(1:19) * (OPT.tau_uniform / T63(1));
end


%% ========================================================================
%  2절  판정식
%  ========================================================================
function [L, H] = uspan(Vk, e, GMIN, GMAX)
% 가로 편차 e = (dw, dq, dth) 로 자른 단면에서 BRT 가 차지하는 du 구간.
%
%   [여기서 한 번 크게 틀렸던 곳]
%   처음에는 트림점 속도(du = 0)에서 시작해 좌우로 뻗어 나가는 길이를 재는
%   방식으로 구했다.  그런데 가속 중인 기체가 놓인 높이에서 자르면 단면이
%   좁아질 뿐 아니라 한쪽으로 치우쳐서, du = 0 자체가 영역 밖일 수 있다.
%   그러면 뻗어 나갈 시작점이 없어 길이가 0 으로 계산되고, 실제로는 안전하게
%   지나간 구간이 위험하다고 오판정된다.  실측에서 네 구간이 통째로 이렇게
%   잘못 나왔다.
%
%   그래서 뻗는 길이가 아니라 구간 자체를 찾는다.  du 축을 훑어 V <= 0 인
%   구간의 양 끝을 돌려준다.  두 값 모두 자기 트림점을 0 으로 삼아 잰다.
%
%   반환값 : 통과 가능한 구간이 없으면 L = 1, H = -1 (즉 H - L < 0)

% 격자 밖 처리.  griddedInterpolant 는 격자 밖을 조회하면 경계값을 그대로
% 돌려주는데, 그 값이 음수라면 안전하다고 오답하게 된다.  명시적으로
% 위험으로 처리해야 한다.
if any([e(1); e(2); e(3)] < GMIN(2:4) | [e(1); e(2); e(3)] > GMAX(2:4))
    L = 1;  H = -1;  return
end

ug = linspace(GMIN(1), GMAX(1), 161);        % du 축을 0.2 간격으로 훑는다
vv = Vk(ug(:), repmat(e(1),161,1), repmat(e(2),161,1), repmat(e(3),161,1));
in = vv(:).' <= 0;                            % 안전영역 안인 격자점

if ~any(in), L = 1;  H = -1;  return, end

% 안쪽 구간이 여러 조각으로 끊겨 있을 수 있으므로 가장 긴 것을 고른다.
d = diff([0 in 0]);
b = find(d ==  1);                            % 각 조각의 시작
f = find(d == -1) - 1;                        % 각 조각의 끝
[~, m] = max(f - b);
L = ug(b(m));  H = ug(f(m));
end


function s = slack(P, k, e)
% 겹침 여유.  0 이상이면 두 BRT 의 du 구간이 트림 간격만큼 겹친다.
%
%       H_k(e) - L_{k+1}(e + 트림차) >= Du_k
%
%   절대 속도로 보면 앞 영역이 u_k + H_k 까지 닿고 뒤 영역이 u_{k+1} + L_{k+1}
%   부터 시작하는데, 앞의 끝이 뒤의 시작보다 오른쪽에 있으면 겹친다.
%   이것을 정리하면 위 식이 된다.  L 은 대개 음수이므로 빼기가 실제로는
%   더하기로 작동한다.
%
%   두 구간이 모두 자기 트림점의 속도를 품고 있을 때는 소박한 형태
%   rho_k + rho_{k+1} >= Du 와 똑같아지지만, 품고 있지 않을 때에도
%   올바르게 답한다는 점이 다르다.
[~, Hk] = uspan(P.V{k},   e,               P.GMIN, P.GMAX);
[Ln, ~] = uspan(P.V{k+1}, e + P.SH(:,k),   P.GMIN, P.GMAX);
s = Hk - Ln - P.du(k);
end


%% ========================================================================
%  3절  예측식
%  ========================================================================
function e = devat(P, t, k, a, tj, DD)
% 시각 t 에서의 가로 편차 e = (dw, dq, dth).  BRT 를 자르는 위치가 된다.
%
%   [dw 와 dth : 계단들의 중첩]
%       dw(t), dth(t) = sum_{j<=k} Dd_j * g(t - t_j)
%
%   편차의 거동이 선형이므로 겹침의 원리가 성립한다.  즉 여러 계단 입력에
%   대한 응답은 각 계단에 대한 응답을 그냥 더한 것과 같다.  구간이 바뀔
%   때마다 목표로 삼는 정상 편차가 d_{k-1} 에서 d_k 로 바뀌므로, 그 차이만큼의
%   계단이 하나 더 얹힌다.  앞 구간의 계단이 아직 자라는 중이면 그 몫이
%   그대로 살아 있다.
%
%   [dq : 미분으로 얻는다]
%       dq(t) = sum_{j<=k} Dd_th,j * g'(t - t_j) - (dth_trim/du) * a_k
%
%   네 성분 중 피치각속도만 성질이 다르다.  가속도를 일정하게 유지하면
%   자세는 결국 d_th 에 머물러 더 이상 돌지 않으므로, dq 의 정상 편차는 0 이고
%   곱할 c 가 없다.  그 대신 dq 는 정의상 피치각이 변하는 속도이므로 위 식을
%   시간에 대해 미분하면 얻어진다.
%
%   뒷항이 필요한 이유 : 트림 자세 자체가 속도에 따라 기울어 간다.  속도가
%   오르면 트림 피치각이 조금씩 변하므로, 기체가 트림을 완벽히 따라가더라도
%   그만큼의 각속도가 생긴다.  편차는 트림점 기준으로 재는 값이므로 빼 준다.
e2 = [0; 0];   % [dw; dth] 누적
q  = 0;        % dq 누적
for j = 1:k
    s  = min(max(t - tj(j), 0), P.GT(end));      % 계단 j 가 얹힌 뒤 흐른 시간
    e2 = e2 + DD(:,j) * interp1(P.GT, P.GV, s);  % g 를 곱해 더한다
    q  = q  + DD(2,j) * interp1(P.GT, P.GD, s);  % g' 를 곱해 더한다
end
q = q - P.dthdu(k) * a(k);
e = [e2(1); q; e2(2)];                           % [dw; dq; dth] 순서로 맞춘다
end


function [s, ew] = worst_slack(P, ak, k, a, tj, dD)
% 후보 가속도 ak 를 넣었을 때 구간 k 에서 가장 얇은 겹침 여유.
%
%   [왜 구간 안의 여러 시점을 다 보는가]
%   인계가 언제 일어날지 우리가 정하지 않기 때문이다.  기체의 속도는 구간
%   안에서 계속 오르므로 어느 순간엔가 뒤 영역 안으로 들어가는데, 그 순간이
%   미리 정해져 있지 않다.  그러므로 구간 안 어느 순간에 인계가 일어나더라도
%   겹침이 성립하도록 전 구간에서 조건을 요구한다.  아홉 시점을 확인한다.
%
%   [왜 정상 편차도 함께 보는가]
%   구간 안만 보면 짧은 구간에서 큰 가속도가 공짜처럼 보인다.  가속도를
%   키우면 구간이 짧아져 편차가 자랄 시간이 없으므로 구간 끝의 편차는 오히려
%   작아진다.  그러나 그 가속도가 끝까지 자랐을 때의 편차는 계속 커지고,
%   대가는 다음 구간에 도착한다.  그래서 g = 1 인 점근값에서도 확인한다.

% 이번 구간이 새로 얹는 계단.  가속도가 아니라 정상 편차의 변화량이다.
dk = ak * P.C([2 4], k);                     % [c_w; c_th] 만 쓴다
if k == 1
    dnew = dk;
else
    dnew = dk - a(k-1) * P.C([2 4], k-1);
end
DD = dD;  DD(:,k) = dnew;
aa = a;   aa(k)   = ak;

Tk = P.du(k) / ak;                           % 이 가속도에서의 구간 길이
s  = inf;  ew = [0;0;0];
TT = [linspace(0, Tk, 9), inf];              % 구간 안 아홉 시점 + 점근값
for n = 1:numel(TT)
    if isinf(TT(n))
        e2 = sum(DD(:,1:k), 2);              % 모든 계단이 다 자란 값 (g = 1)
        e  = [e2(1); -P.dthdu(k)*ak; e2(2)]; % 정상 상태에서 g' = 0
    else
        e = devat(P, tj(k) + TT(n), k, aa, tj, DD);
    end
    v = slack(P, k, e);
    if v < s, s = v;  ew = e; end
end
end


%% ========================================================================
%  4절  풀이
%  ========================================================================
function [a, info] = solve_schedule(P, a_hi, TAU)
% 앞에서부터 한 구간씩 가속도를 정한다.
%
%   구간 k 에 이르렀을 때 앞 구간들의 가속도는 이미 정해져 있으므로, 지금까지
%   얹힌 계단들을 모두 알고 있다.  후보를 훑어 통과하는 것 중 가장 큰 값을
%   고르고, 계단을 얹은 뒤 다음 구간으로 넘어간다.
%
%   [이분법을 쓰면 안 되는 이유]
%   여유가 가속도에 대해 단조롭게 줄어들지 않는다.  편차를 만드는 것은
%   가속도가 아니라 가속도의 변화량이므로, 앞 구간과 같은 값 근처에서 여유가
%   가장 크다.  이분법은 단조성을 전제하므로 이런 자리에서 정반대 끝으로
%   튕겨 나간다.  실제로 그렇게 하다가 두 구간이 최솟값으로 주저앉아
%   천이시간이 여섯 배로 늘어난 적이 있다.
%
%   [세 가지 상한]
%   성립조건  T_k >= tau_k   즉 a_k <= du_k / tau_k
%             구간은 편차가 자리 잡을 시간만큼 지속되어야 한다.  그렇지
%             않으면 조각별로 가속도가 일정하다는 전제 자체가 무너진다.
%   공력범위  a_k <= a_hi(k)
%             공력 모델이 유효한 범위에서 나온 기체 쪽 제약이다.
%   안전조건  겹침 여유 >= 0
%             이것만 별도로 구해 두는 이유는 무엇이 실제로 묶었는지 보려는
%             것이다.  이 기체에서는 19개 중 구간 2 하나만 안전조건이 묶고
%             나머지 18개는 전부 성립조건이 묶는다.
n  = 19;
a  = zeros(1, n);      % 구하려는 답
tj = zeros(1, n+1);    % 각 구간의 시작 시각
dD = zeros(2, n);      % 각 구간이 얹은 계단

info = struct('cap_tau',zeros(1,n), 'cap_aero',zeros(1,n), ...
              'a_safe', zeros(1,n), 'slack',   zeros(1,n), ...
              'bind',   {cell(1,n)});

for k = 1:n
    cap_tau  = P.du(k) / TAU(k);
    cap_aero = a_hi(k);
    cap      = min([cap_tau, cap_aero, 16]);   % 16 은 격자 훑기의 하드 상한

    % (1) 안전조건만 걸었을 때 갈 수 있는 최대.  무엇이 묶었는지 보려고
    %     따로 구한다.  풀이 자체에는 쓰이지 않는다.
    AGs = 0.05 : 0.05 : min(cap_aero, 16);
    oks = false(size(AGs));
    for i = 1:numel(AGs)
        oks(i) = worst_slack(P, AGs(i), k, a, tj, dD) >= 0;
    end
    if any(oks), a_safe = AGs(find(oks,1,'last')); else, a_safe = 0.05; end

    % (2) 세 상한을 모두 적용한 실제 답
    AG = 0.05 : 0.05 : cap;
    ok = false(size(AG));
    for i = 1:numel(AG)
        ok(i) = worst_slack(P, AG(i), k, a, tj, dD) >= 0;
    end
    if any(ok), best = AG(find(ok,1,'last')); else, best = 0.05; end

    a(k) = best;
    info.cap_tau(k)  = cap_tau;
    info.cap_aero(k) = cap_aero;
    info.a_safe(k)   = a_safe;
    info.slack(k)    = worst_slack(P, best, k, a, tj, dD);
    if     a_safe  <= cap,       info.bind{k} = '안전조건';
    elseif cap_tau <= cap_aero,  info.bind{k} = '성립조건';
    else,                        info.bind{k} = '공력범위';
    end

    % (3) 계단을 얹고 다음 구간으로
    dk = best * P.C([2 4], k);
    if k == 1
        dD(:,1) = dk;
    else
        dD(:,k) = dk - a(k-1) * P.C([2 4], k-1);
    end
    tj(k+1) = tj(k) + P.du(k) / best;
end

info.tj = tj;  info.dD = dD;
end


%% ========================================================================
%  5절  검증
%  ========================================================================
function R = verify_schedule(D, a, T_cruise)
% 나온 스케줄을 비선형 시뮬레이터로 실제 비행시킨다.
%
%   [위배의 정의]
%   두 BRT 어디에도 들어 있지 않은 스텝을 센다.  겹침 방법론에서는 둘 중
%   하나에만 들어 있어도 안전하므로 이것이 옳은 척도다.  앵커 k 하나만 놓고
%   보면 구간 후반에 V 가 양수로 커지지만, 그때는 이미 앵커 k+1 안에 들어와
%   있으므로 문제가 아니다.
dt       = 0.01;      % 시뮬레이터 적분 간격 [초]
WDOT     = 11.667;    % 강하율 [ft/s], 트림점을 구한 조건과 같아야 한다
ALT0     = 1600;      % 시작 고도 [ft]
T_SETTLE = 45.0;      % 강하 호버에서 정착시키는 시간 [초]

params = struct('filter_mode','off');   params.T_seg = 2.0;
guam = LpC_GUAM(Config('trim_schedule', params));
guam.reset();
st = guam.saveState();  st.state(3) = -ALT0;  guam.restoreState(st);
p = [0; 0; -ALT0];                      % 기준궤적의 위치 [N; E; D]

% 강하 호버에서 충분히 정착시킨다.  여기서 시작해야 편차가 0 에서 출발한다.
for i = 1:round(T_SETTLE/dt)
    p = p + [0; 0; WDOT*dt];
    guam.step(struct('pos',p, 'vel',[0;0;WDOT], 'chi',0, 'chi_dot',0));
end

R.cov     = false(1,19);   % 구간마다 인계가 실제로 일어났는가
R.worst   = zeros(1,19);   % 구간마다 min(V_k, V_k+1) 의 최댓값
R.out_pct = zeros(1,19);   % 구간마다 두 영역 모두 밖이었던 비율 [%]
R.n_out   = 0;  R.n_tot = 0;

for k = 1:19
    N  = max(round(D.du(k)/a(k)/dt), 1);   % 이 구간의 스텝 수
    v1 = zeros(1,N);   % 앵커 k   의 값함수
    v2 = zeros(1,N);   % 앵커 k+1 의 값함수
    w  = -inf;  no = 0;
    for i = 1:N
        [v1(i), v2(i)] = both_values(guam, D, k);
        w = max(w, min(v1(i), v2(i)));         % 둘 중 나은 쪽이 기준
        if min(v1(i), v2(i)) > 0, no = no + 1; end

        % 기준궤적을 한 걸음 진행시킨다.  속도는 일정 가속도로 오르고
        % 고도는 일정 강하율로 내려간다.
        v = D.UH(k) + a(k)*(i*dt);
        p = p + [v*dt; 0; WDOT*dt];
        guam.step(struct('pos',p, 'vel',[v;0;WDOT], 'chi',0, 'chi_dot',0));
    end

    % 덮임 판정 : 앵커 k 를 벗어나기 전에 앵커 k+1 안으로 들어왔는가.
    %   h1 = 앵커 k   안에 있던 마지막 스텝
    %   h2 = 앵커 k+1 안에 계속 머무르기 시작한 첫 스텝
    j = find(v1 > 0, 1, 'first');  if isempty(j), h1 = N; else, h1 = j-1; end
    j = find(v2 > 0, 1, 'last');   if isempty(j), h2 = 1; else, h2 = j+1; end
    R.cov(k)     = (h2 <= N) && (h2 <= h1 + 1);
    R.worst(k)   = w;
    R.out_pct(k) = 100*no/N;
    R.n_out = R.n_out + no;
    R.n_tot = R.n_tot + N;
end

% 순항 유지.  천이가 끝난 뒤 앵커 20 의 BRT 안에 머무르는지 본다.
Nc = round(T_cruise/dt);  wc = -inf;  noc = 0;
for i = 1:Nc
    [~, ~, v20] = both_values(guam, D, 19);
    wc = max(wc, v20);
    if v20 > 0, noc = noc + 1; end
    p = p + [D.UH(20)*dt; 0; WDOT*dt];
    guam.step(struct('pos',p, 'vel',[D.UH(20);0;WDOT], 'chi',0, 'chi_dot',0));
end
R.cruise_worst = wc;  R.cruise_out = noc;  R.cruise_n = Nc;
end


function [v1, v2, v20] = both_values(guam, D, k)
% 현재 상태를 지평선 기준으로 돌린 뒤 앵커 k, k+1, 20 의 값함수를 조회한다.
%
%   [좌표계를 반드시 맞춰야 한다]
%   트림표와 BRT 의 축은 지평선 기준인데 시뮬레이터가 내주는 상태는 동체
%   기준이다.  기수가 숙여져 있으면 두 기준이 어긋난다.  고속에서 피치가
%   2도만 어긋나도 152 * sin(2도) = 5.3 만큼이 수직속도에 섞여 들어가고,
%   이것을 빠뜨리면 수직속도 편차의 부호까지 뒤집힌다.
s  = guam.state;     % [rn re rd u v w phi theta psi p q r]
th = s(8);           % 피치각

uh =  s(4)*cos(th) + s(6)*sin(th);   % 동체 -> 지평선
wh = -s(4)*sin(th) + s(6)*cos(th);
X  = [uh; wh; s(11); th];            % [u; w; q; th] 지평선 기준

v1  = look(D, k,   X);
v2  = look(D, k+1, X);
v20 = look(D, 20,  X);
end


function v = look(D, k, X)
% 앵커 k 기준으로 편차를 잰 뒤 값함수를 조회한다.
% 격자 밖이면 위험으로 처리한다 (보간기가 경계값을 돌려주는 것을 막는다).
e = X - D.TL(:,k);
if any(e < D.GMIN | e > D.GMAX)
    v = 1;  return
end
v = D.V{k}(e(1), e(2), e(3), e(4));
end


