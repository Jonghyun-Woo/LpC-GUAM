    100*R.cruise_out/R.cruise_n);
end


%% ========================================================================
%  부록  계수 c 를 재는 방법
%  ========================================================================
function C = measure_gain(root, D)
% c_k 를 비선형 시뮬레이터에서 잰다.
%
%   [이것은 탐색이 아니라 동정이다]
%   스케줄을 찾으려고 시뮬레이터를 돌리는 것이 아니라, 폐루프의 계수 하나를
%   측정하는 것이다.  성격이 다르다.
%
%   [왜 선형모델로는 안 되는가]
%   자세 계수 c_th 는 폐루프 선형모델에서도 정확히 나온다 (20개 앵커 전부
%   일치).  그러나 병진속도 계수 c_w 와 c_u 는 선형모델이 고속에서 부호까지
%   틀린다.  자세는 맞히고 병진속도는 못 맞히는 한계이므로 이 두 계수만은
%   비선형 시뮬레이터에서 재야 한다.
%
%   [재는 방법]
%   저장된 스케줄로 날리면서 구간 끝의 편차를 읽는다.  그런데 그 편차는
%   아직 정상값에 도달하지 않은 값이므로, 그때까지 계단들이 얼마나 자랐는지를
%   나타내는 중첩 배율로 나눠서 정상값을 복원한다.
%
%   구간 끝(마지막 세 스텝)에서 읽는 이유는 그 시점이 정상값에 가장 가깝기
%   때문이다.  구간 중간의 최댓값을 쓰면 피치각속도의 과도 꼭짓점을 잡게 되어
%   정상 이득이 아닌 값이 나온다.

S  = load(fullfile(root,'logger','schedule_sim.mat'));
GS = load(fullfile(root,'logger','dev_gain.mat'), 'GT', 'GV');
asch = S.a;        % 날릴 스케줄 [ft/s^2]
du   = S.du_seg;   % 그 스케줄의 구간 간격 [ft/s]

gf = @(t) interp1(GS.GT, GS.GV, min(max(t,0), GS.GT(end)));
tj = [0 cumsum(du./asch)];         % 각 구간 시작 시각
da = [asch(1) diff(asch)];         % 각 구간이 얹는 가속도 계단
Sc = @(t) sum(da .* gf(t - tj(1:19)));   % 시각 t 에서의 중첩 배율

dt = 0.01;  WDOT = 11.667;  ALT0 = 1600;
params = struct('filter_mode','off');  params.T_seg = 2.0;
guam = LpC_GUAM(Config('trim_schedule', params));  guam.reset();
st = guam.saveState();  st.state(3) = -ALT0;  guam.restoreState(st);
p = [0; 0; -ALT0];
for i = 1:round(45/dt)
    p = p + [0; 0; WDOT*dt];
    guam.step(struct('pos',p, 'vel',[0;0;WDOT], 'chi',0, 'chi_dot',0));
end

C = zeros(4,20);  t = 0;
for k = 1:19
    N  = max(round(du(k)/asch(k)/dt), 1);
    bd = zeros(4,1);
    for i = 1:N
        s  = guam.state;  th = s(8);
        uh =  s(4)*cos(th) + s(6)*sin(th);
        wh = -s(4)*sin(th) + s(6)*cos(th);
        e  = [uh; wh; s(11); th] - D.TL(:,k);
        if i >= N-2
            bd = e / max(Sc(t), 0.5);      % 중첩 배율로 나눠 정상값 복원
        end
        v = D.UH(k) + asch(k)*(i*dt);
        p = p + [v*dt; 0; WDOT*dt];
        guam.step(struct('pos',p, 'vel',[v;0;WDOT], 'chi',0, 'chi_dot',0));
        t = t + dt;
    end
    C(:,k) = bd;
end
C(:,20) = C(:,19);      % 마지막 앵커는 직전 값을 쓴다
end


